def playbook_action(urgency: str, segment: str, flags: list[str]) -> dict:
    for pid, u, seg, flag, owner, action in PLAYBOOK:
        if (u is None or u == urgency) and (seg is None or seg == segment) and (flag is None or flag in flags):
            return {"playbook_id": pid, "owner": owner, "text": action}
    raise AssertionError("PLAYBOOK must end with a catch-all entry")


def segment_info(code: str) -> dict:
    name, emoji, group, meaning = SEGMENTS[code]
    return {"code": code, "name": name, "emoji": emoji, "group": group, "meaning": meaning}
